"""Turn per-frame analysis stats into the response the React frontend expects.

The frontend (``frontend/src/App.jsx``) reads exactly these fields:
    data.score      — number, 0-100
    data.breakdown  — object of label -> display value (rendered by ScorePanel)
    data.messages   — [{role, text}] (rendered by ChatPanel)
    data.links      — [{title, url, tag}] (rendered by VideoLinks)

Extra fields (frames_analyzed, reps_estimated, ...) are included for
transparency; the frontend ignores what it does not use.

Coaching messages are *not* generated by an LLM and do not change the
score. They are rule-based, derived from comparing the engineered
features on frames the Random Forest flagged as bad form against the
frames it flagged as good form. If a feature is higher on bad-form
frames, the coach names that specific issue.
"""

from __future__ import annotations

# Tutorial links verified 2026-11-11 (YouTube). Do not swap in unlisted
# videos without checking the URL still resolves.
TUTORIAL_LINKS = [
    {
        "title": "STOP, You're Training Your Biceps All Wrong! — ATHLEAN-X",
        "url": "https://www.youtube.com/watch?v=BJ6UVAUUJIs",
        "tag": "Common curl mistakes",
    },
    {
        "title": "Bicep Curls — Dumbbell Form & Technique",
        "url": "https://www.youtube.com/watch?v=XE_pHwbst04",
        "tag": "Dumbbell curl walkthrough",
    },
    {
        "title": "How To: Standing Dumbbell Bicep Curl",
        "url": "https://www.youtube.com/watch?v=d_TfENBv38s",
        "tag": "Standing curl basics",
    },
]

# (feature key, display name, coaching text)
ISSUE_RULES = [
    (
        "back_lean",
        "Back lean / swing",
        "Your back leaned and swung more on the bad-form frames. Brace your "
        "core, keep your torso still, and don't swing the weight up — if you "
        "have to swing, the weight is too heavy.",
    ),
    (
        "elbow_flare",
        "Elbow flare",
        "Your elbows drifted away from your sides on the bad-form frames. "
        "Pin your elbows to your torso and keep them still for the whole rep.",
    ),
    (
        "shoulder_shrug",
        "Shoulder shrug",
        "Your shoulders shrugged up on the bad-form frames. Drop your "
        "shoulders down and back before each rep and keep them there.",
    ),
    (
        "wrist_velocity",
        "Wrist speed / momentum",
        "Your wrist moved fast between frames on the bad-form reps — you are "
        "using momentum. Slow the rep down, especially the lowering phase "
        "(aim for 2–3 seconds down).",
    ),
    (
        "neck_angle",
        "Neck / head position",
        "Your neck and head position shifted on the bad-form frames. Keep "
        "your head neutral and your gaze forward.",
    ),
]


def _mean(rows, key):
    values = [r[key] for r in rows if key in r]
    return sum(values) / len(values) if values else 0.0


def build_response(stats):
    """Build the /analyze response dict from ``analyze_video`` stats."""
    with_person = stats["frames_with_person"]
    good = stats["frames_good"]
    bad = stats["frames_bad"]
    score = int(round(100 * good / with_person)) if with_person else 0
    mean_prob = stats["mean_probability"]

    if score >= 80:
        verdict = "Solid set — most frames were classified as good form."
    elif score >= 60:
        verdict = "Mostly good form, with some bad-form frames. See the issues below."
    elif score >= 40:
        verdict = "Mixed set — about half the frames showed good form. See the issues below."
    else:
        verdict = "Most frames were flagged as bad form. Slow down, lighten the weight, and work on the issues below."

    messages = [
        {
            "role": "coach",
            "text": (
                f"Score {score}/100 across {with_person} analysed frames "
                f"({good} good, {bad} bad, {stats['reps_estimated']} estimated "
                f"rep(s)). {verdict}"
            ),
        }
    ]

    # Rank issues by how much worse the feature was on bad-form frames
    # than on good-form frames, and report the top two.
    good_rows = stats["good_frame_features"]
    bad_rows = stats["bad_frame_features"]
    ranked = []
    for key, _name, text in ISSUE_RULES:
        if good_rows and bad_rows:
            gap = _mean(bad_rows, key) - _mean(good_rows, key)
            # wrist_velocity is on a ~0-100 scale, the rest are small
            # angles / normalised distances; normalise the gap so the
            # ranking is comparable.
            scale = 10.0 if key == "wrist_velocity" else 1.0
            ranked.append((gap / scale, text))
    ranked.sort(reverse=True)
    for gap, text in ranked[:2]:
        if gap > 0:
            messages.append({"role": "coach", "text": text})

    if not bad_rows:
        messages.append(
            {
                "role": "coach",
                "text": "No bad-form frames in this clip. Keep the elbows pinned, "
                "the torso still, and the lowering phase slow.",
            }
        )
    elif not good_rows:
        # Every frame was flagged, so there are no good frames in this
        # clip to compare against — the per-feature comparison above
        # cannot run. Say so plainly: this pattern also happens when
        # the recording setup differs a lot from the training videos
        # (different person, camera angle, or framing), and the score
        # should not be taken at face value in that case.
        messages.append(
            {
                "role": "coach",
                "text": "Every frame was flagged as bad form, so I can't compare "
                "good vs bad frames inside this clip. That can also happen "
                "when the recording setup differs a lot from the training "
                "videos (different person, angle, or framing). If this set "
                "looked like good form to you, re-record facing the camera "
                "with your full upper body in frame and try again.",
            }
        )

    breakdown = {
        "Form score": f"{score} / 100",
        "Good-form frames": f"{good} / {with_person}"
        + (f" ({100 * good / with_person:.0f}%)" if with_person else ""),
        "Mean confidence": f"{mean_prob * 100:.0f}%",
        "Reps (estimated)": str(stats["reps_estimated"]),
        "Avg back lean": f"{_mean(stats['all_frame_features'], 'back_lean'):.1f} deg",
        "Avg elbow flare": f"{_mean(stats['all_frame_features'], 'elbow_flare'):.3f}",
        "Avg wrist velocity": f"{_mean(stats['all_frame_features'], 'wrist_velocity'):.1f}",
        "Avg shoulder shrug": f"{_mean(stats['all_frame_features'], 'shoulder_shrug'):.3f}",
    }

    return {
        "score": score,
        "breakdown": breakdown,
        "messages": messages,
        "links": TUTORIAL_LINKS if score < 100 else TUTORIAL_LINKS[:1],
        # Extra, transparent diagnostics (ignored by the current frontend):
        "frames_total": stats["frames_total"],
        "frames_analyzed": stats["frames_analyzed"],
        "frames_with_person": with_person,
        "frames_good": good,
        "frames_bad": bad,
        "reps_estimated": stats["reps_estimated"],
        "mean_confidence": round(mean_prob, 3),
        "verdict": verdict,
        "model": "bicep_model_v2.pkl (Random Forest, YOLOv8n-pose)",
    }
